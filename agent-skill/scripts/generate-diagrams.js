function fit(str, size, maxW) {
  const w = estWidth(str, size);
  if (w > maxW + 1) warnings.push(`${current}: 「${str}」推定幅 ${Math.round(w)}px > 枠 ${Math.round(maxW)}px`);
}

function tx(d, x, y, str, o = {}) {
  const size = o.size ?? 15;
  if (o.maxW) fit(str, size, o.maxW);
  d.text(r1(x), r1(y), str, size, o.color ?? INK, o.weight ?? 400, o.anchor ?? 'start', undefined, o.halo ?? null);
}

function rc(d, x, y, w, h, o = {}) {
  const target = o.bg ? d.bgParts : d.parts;
  const stroke = o.stroke
    ? ` stroke="${o.stroke}" stroke-width="${o.sw ?? 1.6}"${o.dash ? ` stroke-dasharray="${o.dash}"` : ''}`
    : ' stroke="none"';
  target.push(`<rect x="${r1(x)}" y="${r1(y)}" width="${r1(w)}" height="${r1(h)}" rx="${o.rx ?? 10}" fill="${o.fill ?? '#fff'}"${stroke}/>`);
}

function pth(d, dstr, o = {}) {
  const target = o.bg ? d.bgParts : d.parts;
  const stroke = o.stroke
    ? ` stroke="${o.stroke}" stroke-width="${o.sw ?? 2}" stroke-linejoin="round"${o.dash ? ` stroke-dasharray="${o.dash}"` : ' stroke-linecap="round"'}`
    : ' stroke="none"';
  target.push(`<path d="${dstr}" fill="${o.fill ?? 'none'}"${stroke}/>`);
}

function circle(d, cx, cy, r, fill, stroke = 'none', sw = 2) {
  d.parts.push(`<circle cx="${r1(cx)}" cy="${r1(cy)}" r="${r}" fill="${fill}"${stroke === 'none' ? '' : ` stroke="${stroke}" stroke-width="${sw}"`}/>`);
}

function head(d, from, to, color, size = 12) {
  const a = Math.atan2(to[1] - from[1], to[0] - from[0]);
  const w = size * 0.55;
  const bx = to[0] - size * Math.cos(a);
  const by = to[1] - size * Math.sin(a);
  const px = -Math.sin(a) * w;
  const py = Math.cos(a) * w;
  pth(d, `M${r1(bx + px)} ${r1(by + py)} L${r1(to[0])} ${r1(to[1])} L${r1(bx - px)} ${r1(by - py)} Z`, { fill: color });
}

/** 折れ線の矢印。pts=[[x,y],...]。 */
function arrow(d, pts, color, o = {}) {
  const dstr = 'M' + pts.map((p) => `${r1(p[0])} ${r1(p[1])}`).join(' L');
  pth(d, dstr, { stroke: color, sw: o.sw ?? 2, dash: o.dash });
  if (o.head !== false) head(d, pts[pts.length - 2], pts[pts.length - 1], color, o.headSize ?? 12);
}

/** 丸みのあるラベル（文字幅から自動で幅を決める）。幅を返す。 */
function pill(d, cx, cy, str, tone, o = {}) {
  const size = o.size ?? 13.5;
  const w = Math.ceil(estWidth(str, size) + (o.padX ?? 12) * 2);
  const h = o.h ?? Math.round(size * 2);
  rc(d, cx - w / 2, cy - h / 2, w, h, { fill: o.fill ?? '#fff', stroke: tone.c, rx: h / 2, sw: 1.4 });
  tx(d, cx, cy + size * 0.36, str, { size, color: o.color ?? tone.t, weight: o.weight ?? 700, anchor: 'middle' });
  return w;
}

/** 塗りつぶしのタグ。x は左端、cy は縦中心。幅を返す。 */
function tag(d, x, cy, label, tone, o = {}) {
  const size = o.size ?? 13;
  const w = Math.ceil(estWidth(label, size) + 18);
  const h = o.h ?? 24;
  rc(d, x, cy - h / 2, w, h, { fill: tone.c, rx: 6 });
  tx(d, x + w / 2, cy + size * 0.36, label, { size, color: '#fff', weight: 700, anchor: 'middle' });
  return w;
}

function badge(d, cx, cy, label, color, r = 14, size = 14) {
  circle(d, cx, cy, r, color);
  tx(d, cx, cy + size * 0.36, label, { size, color: '#fff', weight: 700, anchor: 'middle' });
}

/** 見出し帯つきカード。lines は文字列か {t,color,weight,size,indent,gap,mono}。 */
function card(d, x, y, w, h, tone, title, lines = [], o = {}) {
  const hh = o.hh ?? (o.sub ? 62 : 46);
  const rx = 12;
  rc(d, x, y, w, h, { fill: o.fill ?? '#fff', rx });
  pth(d, `M${x} ${y + hh} V${y + rx} Q${x} ${y} ${x + rx} ${y} H${x + w - rx} Q${x + w} ${y} ${x + w} ${y + rx} V${y + hh} Z`, { fill: tone.f });
  pth(d, `M${x} ${y + hh} H${x + w}`, { stroke: tone.s, sw: 1.4 });
  rc(d, x, y, w, h, { fill: 'none', stroke: tone.c, rx, sw: o.sw ?? 1.6, dash: o.dash });
  const center = o.align === 'middle';
  const bOff = o.badge ? 30 : 0;
  const tX = center ? x + w / 2 : x + 18 + bOff;
  if (o.badge) badge(d, x + 30, y + (o.sub ? 31 : hh / 2), o.badge, tone.c, 13, 13.5);
  const tY = o.sub ? y + 28 : y + hh / 2 + 6.5;
  tx(d, tX, tY, title, { size: o.ts ?? 17.5, color: tone.t, weight: 700, anchor: center ? 'middle' : 'start', maxW: w - 36 - bOff });
  if (o.sub) tx(d, tX, y + 50, o.sub, { size: 13, color: MUTED, anchor: center ? 'middle' : 'start', maxW: w - 36 - bOff });
  const lh = o.lh ?? 23;
  let ly = y + hh + (o.top ?? 28);
  for (const raw of lines) {
    const ln = typeof raw === 'string' ? { t: raw } : raw;
    if (ln.gap) { ly += ln.gap; continue; }
    const size = ln.size ?? o.ls ?? 14.5;
    const lx = center ? x + w / 2 : x + 18 + (ln.indent ?? 0);
    tx(d, lx, ly, ln.t, { size, color: ln.color ?? INK, weight: ln.weight ?? 400, anchor: center ? 'middle' : 'start', maxW: w - 36 - (ln.indent ?? 0) });
    ly += ln.lh ?? lh;
  }
  return { x, y, w, h, cx: x + w / 2, cy: y + h / 2, bottom: y + h, right: x + w };
}

/** 枠だけの箱に中央揃えの複数行。lines[0] を太字の見出しにする。 */
function box(d, x, y, w, h, tone, lines, o = {}) {
  rc(d, x, y, w, h, { fill: o.fill ?? tone.f, stroke: tone.c, rx: o.rx ?? 10, sw: o.sw ?? 1.7, dash: o.dash });
  const lh = o.lh ?? 21;
  const n = lines.length;
  const y0 = y + h / 2 - ((n - 1) * lh) / 2 + 5;
  lines.forEach((raw, i) => {
    const ln = typeof raw === 'string' ? { t: raw } : raw;
    const first = i === 0 && !o.plain;
    tx(d, x + w / 2, y0 + i * lh, ln.t, {
      size: ln.size ?? (first ? (o.ts ?? 15.5) : (o.ls ?? 13.5)),
      color: ln.color ?? (first ? tone.t : INK),
      weight: ln.weight ?? (first ? 700 : 400),
      anchor: 'middle',
      maxW: w - 16,
    });
  });
  return { x, y, w, h, cx: x + w / 2, cy: y + h / 2, bottom: y + h, right: x + w };
}

/** データベース（円柱）アイコン。 */
function cylinder(d, cx, y, w, h, tone) {
  const rx = w / 2;
  const ry = 9;
  pth(d, `M${cx - rx} ${y + ry} V${y + h - ry} A${rx} ${ry} 0 0 0 ${cx + rx} ${y + h - ry} V${y + ry}`, { fill: tone.f, stroke: tone.c, sw: 1.8 });
  d.parts.push(`<ellipse cx="${cx}" cy="${y + ry}" rx="${rx}" ry="${ry}" fill="#fff" stroke="${tone.c}" stroke-width="1.8"/>`);
  pth(d, `M${cx - rx} ${y + ry + 14} A${rx} ${ry} 0 0 0 ${cx + rx} ${y + ry + 14}`, { stroke: tone.c, sw: 1.2 });
}

/** ファイルツリーを描く。rows = [{t, depth, tone?, note?}] */
function tree(d, x, y, rows, o = {}) {
  const lh = o.lh ?? 27;
  rows.forEach((r, i) => {
    const yy = y + i * lh;
    const ix = x + (r.depth ?? 0) * 22;
    if ((r.depth ?? 0) > 0) pth(d, `M${ix - 14} ${yy - 18} V${yy - 5} H${ix - 4}`, { stroke: '#cbd5e1', sw: 1.4 });
    tx(d, ix, yy, r.t, { size: o.size ?? 14.5, color: r.tone ? r.tone.t : INK, weight: r.bold || r.tone ? 700 : 400, maxW: o.maxW });
    if (r.note) tx(d, o.noteX ?? ix + estWidth(r.t, o.size ?? 14.5) + 12, yy, r.note, { size: 12.5, color: MUTED });
  });
  return y + (rows.length - 1) * lh;
}

function done(d, contentEnd, notes) {
  notes.forEach((n) => fit(n, 16, 1120));
  d.finish(contentEnd + 30 + notes.length * 27 + 48, notes);
}

function start(spec, title, subtitle) {
  const [where, file] = spec.includes(':') ? spec.split(':') : ['', spec];
  current = file;
  fit(title, 27, 1144);
  fit(subtitle, 16, 1144);
  return new DRAWING[where](file, title, subtitle);
}

