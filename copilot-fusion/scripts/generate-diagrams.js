class Sequence extends Drawing {
  phase(label,repeat=false){
    // 背景帯は bgParts（ライフラインの裏）へ描画し、縦線が消えないようにする。
    this.rect(24,this.y,1152,36,'#f8fafc','#e2e8f0',6,this.bgParts);
    this.text(40,this.y+24,label,16.5,'#334155',700,'start',[32,this.y+2,1136,32],'#f8fafc');
    this.y+=60;
    if(repeat){
      for(const a of actors){
        this.rect(a.x-90,this.y-10,180,32,a.fill,a.color,6);
        this.text(a.x,this.y+12,a.name,14.5,a.color,700,'middle',[a.x-84,this.y-8,168,28]);
      }
      this.y+=46;
    }
  }
  message(from,to,lines,reply=false){
    lines=Array.isArray(lines)?lines:[lines];
    const a=palette[from],b=palette[to],center=(a.x+b.x)/2,top=this.y;
    const maxW=Math.max(...lines.map(l=>estWidth(l,16.5)));
    const textLeft=center-maxW/2-4, textRight=center+maxW/2+4;
    // 文字が中間の縦線に重なるときだけ、文字自体の輪郭を白抜き(halo)にし、白い横帯は描かない。
    const crossesLine=actors.some(act=>textLeft<act.x&&act.x<textRight);
    const halo=crossesLine?'#ffffff':null;
    lines.forEach((s,i)=>this.text(center,top+22+i*26,s,16.5,a.color,600,'middle',[center-260,top-1,520,28],halo));
    const arrow=top+lines.length*26+12;
    this.line(a.x,arrow,b.x,arrow,from,reply);
    this.y=arrow+24;
  }
  action(id,lines){
    lines=Array.isArray(lines)?lines:[lines];const a=palette[id],h=lines.length*26+20;
    this.rect(a.x-88,this.y,176,h,a.fill,a.color,8);
    lines.forEach((s,i)=>this.text(a.x,this.y+27+i*26,s,15.5,a.color,500,'middle',[a.x-82,this.y+2,164,h-4]));
    this.y+=h+22;
  }
  note(lines){
    lines=Array.isArray(lines)?lines:[lines];
    this.noteAt(this.y,lines);
    this.y+=lines.length*27+48;
  }
  save(notes){this.finish(this.y+34+notes.length*27+56,notes,true);}
}

