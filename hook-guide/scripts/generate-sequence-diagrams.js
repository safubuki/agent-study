#!/usr/bin/env node
// 列順・名前・配色を一か所で管理し、4枚のシーケンス図を生成する。
// 実行: node hook-guide/scripts/generate-sequence-diagrams.js
const path = require('node:path');
const {
  createDiagramKit,
  defineActors,
  writeQaReport,
} = require('../../scripts/svg-diagram-kit');

const outputDir = path.resolve(__dirname, '../docs/assets');
const actors = defineActors([
  { id: 'user', name: 'ユーザー', sub: 'チャットで依頼', role: 'slate' },
  { id: 'host', name: 'AI アプリ', sub: '会話と実行を管理', role: 'blue' },
  { id: 'model', name: 'AI モデル', sub: '解釈・推論・返答', role: 'violet' },
  { id: 'hook', name: 'フック', sub: '登録した処理を実行', role: 'emerald' },
  { id: 'tool', name: '作業・検査ツール', sub: '編集・検索・テスト', role: 'cyan' },
  { id: 'app', name: '通知先アプリ', sub: '状態の受信・表示', role: 'amber' },
]);

// 共通キットへ既存フック図の余白・ヘッダー微調整値を渡して出力互換を保つ。
const { Sequence } = createDiagramKit({
  outputDir,
  actors,
  markerEntries: actors,
  generatorComment: '<!-- Generated by ../../scripts/generate-sequence-diagrams.js. -->',
  descSuffix: ' 列順はユーザー、AI アプリ、AI モデル、フック、作業・検査ツール、通知先アプリ。上から下へ時間が進む。',
  defsInline: false,
  layout: {
    titleY: 47,
    subtitleY: 80,
    subtitleBoundsY: 58,
    footerBoxH: 32,
    footerTextOffsetY: 16,
    footerTextSize: 14.5,
    footerBoundsH: 28,
    sequenceLegend: {
      y: 107,
      size: 13,
      boundsY: 88,
      text: '全シーケンス図で列順と色を固定　上→下が時間　矢印の色＝送り手　実線＝依頼・通知　横破線＝結果・応答',
    },
  },
  noteStyle: {
    x: 34,
    w: 1132,
    padH: 18,
    rx: 8,
    textX: 48,
    textOffsetY: 27,
    boundsX: 42,
    boundsOffsetY: 2,
    boundsW: 1116,
    boundsPadH: 14,
    gapAfter: 24,
    footerTopGap: 38,
    footerBottomMargin: 24,
  },
});

function beginRequest(s, request) {
  s.phase('① ユーザーがチャットで依頼する');
  s.action('user', ['指示を入力する']);
  s.message('user', 'host', request);
}

function beginModelWork(s) {
  s.message('host', 'model', '指示を渡す');
  s.action('model', ['依頼を解釈する', '作業内容を考える']);
  s.message('model', 'host', '作業の実行を提案', true);
}

function runWork(s) {
  s.message('host', 'tool', '編集・検索などを実行');
  s.message('tool', 'host', '処理結果を返す', true);
  s.message('host', 'model', '結果を渡す');
  s.action('model', ['結果から返答を作る']);
  s.message('model', 'host', '返答内容を返す', true);
  s.message('host', 'user', '返答を表示する', true);
}

const diagrams = [];
let s = new Sequence('hook-status-notification-sequence.svg', '例1：依頼から、返答終了をアプリで知らせるまで', '返答終了に通知フックを登録した例。ユーザーの依頼・AI の処理・アプリへの通知を順にたどる。');
beginRequest(s, ['チャットで依頼', '「コードを直して」']);
s.phase('② AI が作業し、ユーザーへの返答を作る');
beginModelWork(s);
runWork(s);
s.phase('③ 返答終了のイベントで、フックから通知先アプリへ送る', true);
s.message('host', 'hook', ['Claude: Stop', 'Copilot: agentStop']);
s.action('hook', ['イベントを読む', '通知形式に変換']);
s.message('hook', 'app', ['HTTP POST などで送信', 'state = turn_ended']);
s.action('app', ['受信した状態を保存', '表示・音を更新']);
s.message('app', 'user', '終了バッジや音で知らせる');
s.message('app', 'hook', '受信結果を返す', true);
s.message('hook', 'host', 'フック処理を終了', true);
s.message('host', 'user', 'このターンは停止', true);
diagrams.push(s.finish([
  'Stop / agentStop は返答終了の節目。成果物の成功判定とは別で、turn_ended は通知用に自分で付ける状態名。',
  '開始やツール実行なども、対応イベントを登録すれば同じ受信口へ送れる。検査と組み合わせる場合は例4を参照。',
  '返答表示は途中から順次進む場合もある。図では、返答を表示する流れとターンの停止を分けて示している。',
]));

s = new Sequence('hook-prompt-sequence.svg', '例2：チャット送信時に処理し、その後 AI が返答する', 'ユーザーが送信した直後にフックが動く。通知先アプリを使わず、手元で記録や前提情報の収集を行う例。');
beginRequest(s, ['チャットで依頼', '「この変更を調べて」']);
s.phase('② AI に渡す前に、送信時フックを呼び出す');
s.message('host', 'hook', ['Claude: UserPromptSubmit', 'Copilot: userPromptSubmitted']);
s.action('hook', ['ログを記録する', '前提情報を集める']);
s.phase('分岐 A：Claude Code の場合');
s.message('hook', 'host', ['additionalContext を返す', '検査で送信を止めることも可能'], true);
s.message('host', 'model', ['許可された場合', '指示＋追加情報を渡す']);
s.phase('分岐 B：Copilot の設定ファイルの command フックの場合');
s.message('hook', 'host', ['処理を終了する', '返した本文は採用されない'], true);
s.message('host', 'model', '元の指示を渡す');
s.phase('③ ここからは A・B 共通：AI が処理し、ユーザーに返答する', true);
s.action('model', ['依頼を解釈する', '必要な内容を考える']);
s.message('model', 'host', '返答内容を返す', true);
s.message('host', 'user', '調査結果を表示する', true);
s.action('user', ['返答を読む', '必要なら次を質問']);
diagrams.push(s.finish([
  'A と B は環境別の分岐で、連続して実行される処理ではない。Claude 側で送信を止めた場合は AI には渡さない。',
  'この例では作業・検査ツールと通知先アプリは使わない。全図で同じ列順を保つため、列を残している。',
  'Copilot の sessionStart で開始時の情報を追加できるが、送信のたびに前提を更新する代用にはならない。',
]));

s = new Sequence('hook-tool-sequence.svg', '例3：ユーザーの依頼から、編集前の検査・編集後の整形まで', 'コード変更の依頼を受けた AI がツールを使う例。フックが入る位置を、依頼と返答の間で確認する。');
beginRequest(s, ['チャットで依頼', '「この箇所を直して」']);
s.phase('② AI が依頼を読み、編集ツールの利用を提案する');
beginModelWork(s);
s.phase('③ ツールを実行する前に、フックで対象を検査する', true);
s.message('host', 'hook', ['Claude: PreToolUse', 'Copilot: preToolUse']);
s.action('hook', ['禁止条件を検査']);
s.message('hook', 'host', ['許可・拒否を返す', '禁止対象なら deny'], true);
s.note('拒否ならツールを実行せず、理由を AI に返す。以下は、許可された場合の流れ。');
s.phase('④ 編集を実行し、成功後にフックで整える');
s.message('host', 'tool', '編集ツールを実行');
s.message('tool', 'host', '成功した結果を返す', true);
s.message('host', 'hook', ['Claude: PostToolUse', 'Copilot: postToolUse']);
s.action('hook', ['対象ファイルを整形', '軽量な検査を実行']);
s.message('hook', 'host', '補足や検査結果を返す', true);
s.phase('⑤ 結果を踏まえて返答し、ユーザーが確認する');
s.message('host', 'model', '結果と補足を渡す');
s.action('model', ['結果から返答を作る']);
s.message('model', 'host', '返答内容を返す', true);
s.message('host', 'user', '変更内容を表示する', true);
s.action('user', ['変更内容を確認']);
diagrams.push(s.finish([
  '対象ツールや引数は環境で異なる。編集ツールの検査だけでは、シェル経由の書き込みまで覆えない。',
  '成功後のフックは実行済みの操作を取り消さない。整形後の最新ファイルは、必要に応じて AI に再読込させる。',
  '通知先アプリはこの例では使わない。ユーザー・AI アプリ・AI モデルの列は、ほかの図と同じ位置・色。',
]));

s = new Sequence('hook-completion-gate-sequence.svg', '例4：依頼・作業・返答を経て、終了時の検査で差し戻す', 'ユーザーが実装を頼むところから始める。返答が得られた後、ターンを終える節目で検査フックが動く。');
beginRequest(s, ['チャットで依頼', '「この機能を作って」']);
s.phase('② AI が作業し、その結果から返答を作る');
beginModelWork(s);
runWork(s);
s.phase('③ このターンを終える節目で、検査フックを呼び出す', true);
s.message('host', 'hook', ['Claude: Stop', 'Copilot: agentStop']);
s.message('hook', 'tool', 'テストを実行');
s.message('tool', 'hook', '合否と詳細を返す', true);
s.phase('分岐 A：不合格で、差し戻し回数の上限内');
s.message('hook', 'host', ['decision: block', 'reason: 修正すべき内容'], true);
s.message('host', 'model', ['理由を渡す', '修正を依頼']);
s.action('model', ['修正内容を考える']);
s.note(['ユーザーの再依頼を待たずに、②の作業の流れへ戻る。', 'ツールで修正し、返答を作り直した後、再び③の停止イベントで検査する。']);
s.phase('分岐 B：合格した場合');
s.message('hook', 'host', '停止を許可する', true);
s.message('host', 'user', 'このターンは停止', true);
s.action('user', ['返答と成果物を確認', '必要なら次を依頼']);
diagrams.push(s.finish([
  'A と B は合否の分岐。返答表示と検査のタイミングは区別し、返答が得られただけで成功と判定しない。',
  'stop_hook_active や回数の上限で、終わらない差し戻しを避ける。上限で通した場合も「検査合格」と扱わない。',
  '通知先アプリも使う場合は、検査結果を決めてから通知する。別の停止フックによる差し戻しにも注意する。',
]));

if (process.argv.includes('--qa')) {
  const qaPath = path.resolve(__dirname, '../../output/playwright/sequence-regions.json');
  writeQaReport(qaPath, { actors, diagrams });
}
console.log(`Generated ${diagrams.length} sequence diagrams with the same ${actors.length} participants.`);
