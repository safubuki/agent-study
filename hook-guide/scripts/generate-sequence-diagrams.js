s = new Sequence('hook-completion-gate-sequence.svg', '例4：依頼・作業・返答を経て、終了時の検査で差し戻す', 'ユーザーが実装を頼むところから始める。返答が得られた後、ターンを終える節目で検査フックが動く。');
beginRequest(s, ['チャットで依頼', '「この機能を作って」']);
s.phase('② AI が作業し、その結果から返答を作る');
beginModelWork(s);
runWork(s);
s.phase('③ このターンを終える節目で、検査フックを呼び出す');
s.message('host', 'hook', ['Claude: Stop', 'Copilot: agentStop']);
s.message('hook', 'tool', 'テストを実行');
