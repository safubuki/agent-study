function fit(str, size, maxW) {
  const w = estWidth(str, size);
  if (w > maxW + 1) warnings.push(`${current}: 「${str}」推定幅 ${Math.round(w)}px > 枠 ${Math.round(maxW)}px`);
}

function tx(d, x, y, str, o = {}) {
  const size = o.size ?? 15;
  if (o.maxW) fit(str, size, o.maxW);
  d.text(r1(x), r1(y), str, size, o.color ?? INK, o.weight ?? 400, o.anchor ?? 'start', undefined, o.halo ?? null);
}

function rc(d, x, y, w, h, o = {}) {
  const target = o.bg ? d.bgParts : d.parts;
  const stroke = o.stroke
    ? ` stroke="${o.stroke}" stroke-width="${o.sw ?? 1.6}"${o.dash ? ` stroke-dasharray="${o.dash}"` : ''}`
    : ' stroke="none"';
  target.push(`<rect x="${r1(x)}" y="${r1(y)}" width="${r1(w)}" height="${r1(h)}" rx="${o.rx ?? 10}" fill="${o.fill ?? '#fff'}"${stroke}/>`);
}

function pth(d, dstr, o = {}) {
  const target = o.bg ? d.bgParts : d.parts;
  const stroke = o.stroke
    ? ` stroke="${o.stroke}" stroke-width="${o.sw ?? 2}" stroke-linejoin="round"${o.dash ? ` stroke-dasharray="${o.dash}"` : ' stroke-linecap="round"'}`
    : ' stroke="none"';
  target.push(`<path d="${dstr}" fill="${o.fill ?? 'none'}"${stroke}/>`);
}

function circle(d, cx, cy, r, fill, stroke = 'none', sw = 2) {
  d.parts.push(`<circle cx="${r1(cx)}" cy="${r1(cy)}" r="${r}" fill="${fill}"${stroke === 'none' ? '' : ` stroke="${stroke}" stroke-width="${sw}"`}/>`);
}

/** 矢じり。open=true は SysML の依存関係で使う「開いた矢じり（V字）」。 */
function head(d, from, to, color, open = false, size = 12) {
  const a = Math.atan2(to[1] - from[1], to[0] - from[0]);
  const w = size * 0.55;
  const bx = to[0] - size * Math.cos(a);
  const by = to[1] - size * Math.sin(a);
  const px = -Math.sin(a) * w;
  const py = Math.cos(a) * w;
  const p1 = `${r1(bx + px)} ${r1(by + py)}`;
  const p2 = `${r1(bx - px)} ${r1(by - py)}`;
  if (open) pth(d, `M${p1} L${r1(to[0])} ${r1(to[1])} L${p2}`, { stroke: color, sw: 2 });
  else pth(d, `M${p1} L${r1(to[0])} ${r1(to[1])} L${p2} Z`, { fill: color });
}

/** 折れ線の矢印。pts=[[x,y],...]。dash で点線、open で開いた矢じり。 */
function arrow(d, pts, color, o = {}) {
  const dstr = 'M' + pts.map((p) => `${r1(p[0])} ${r1(p[1])}`).join(' L');
  pth(d, dstr, { stroke: color, sw: o.sw ?? 2, dash: o.dash });
  if (o.head !== false) head(d, pts[pts.length - 2], pts[pts.length - 1], color, o.open, o.headSize ?? 12);
}

/** SysML の依存関係（«deriveReqt» «satisfy» «verify» など）：点線＋開いた矢じり。 */
function dep(d, pts, color, label, labelAt) {
  arrow(d, pts, color, { dash: '7 5', open: true });
  if (label) {
    const [lx, ly] = labelAt ?? [(pts[0][0] + pts[pts.length - 1][0]) / 2, (pts[0][1] + pts[pts.length - 1][1]) / 2];
    pill(d, lx, ly, label, { c: color, t: color }, { size: 12.5 });
  }
}

/** 包含（containment）の ⊕ 記号。親の側に付ける。 */
function crosshair(d, cx, cy, color, r = 9) {
  circle(d, cx, cy, r, '#fff', color, 2);
  pth(d, `M${cx - r} ${cy} H${cx + r} M${cx} ${cy - r} V${cy + r}`, { stroke: color, sw: 2 });
}

/** 親（px,py=親の下辺）から子の上辺へ、⊕ 付きの木構造の線を引く。 */
function containTree(d, px, py, kids, busY, color) {
  const cy = py + 9;
  pth(d, `M${px} ${cy + 9} V${busY}`, { stroke: color, sw: 2 });
  const xs = kids.map((k) => k[0]).concat(px);
  pth(d, `M${Math.min(...xs)} ${busY} H${Math.max(...xs)}`, { stroke: color, sw: 2 });
  kids.forEach(([x, y]) => pth(d, `M${x} ${busY} V${y}`, { stroke: color, sw: 2 }));
  crosshair(d, px, cy, color);
}

/** 丸みのあるラベル（文字幅から自動で幅を決める）。 */
function pill(d, cx, cy, str, tone, o = {}) {
  const size = o.size ?? 13.5;
  const w = Math.ceil(estWidth(str, size) + (o.padX ?? 12) * 2);
  const h = o.h ?? Math.round(size * 2);
  rc(d, cx - w / 2, cy - h / 2, w, h, { fill: o.fill ?? '#fff', stroke: tone.c, rx: h / 2, sw: 1.4 });
  tx(d, cx, cy + size * 0.36, str, { size, color: o.color ?? tone.t ?? tone.c, weight: o.weight ?? 700, anchor: 'middle' });
  return w;
}

/** 用語のマーク（要望・要求・要件・仕様・設計）。x は左端、cy は縦中心。幅を返す。 */
function termTag(d, x, cy, term, o = {}) {
  const tone = TERM[term];
  const size = o.size ?? 13;
  const label = o.label ?? term;
  const w = Math.ceil(estWidth(label, size) + 20);
  const h = o.h ?? 24;
  rc(d, x, cy - h / 2, w, h, { fill: tone.c, rx: 6 });
  tx(d, x + w / 2, cy + size * 0.36, label, { size, color: '#fff', weight: 700, anchor: 'middle' });
  return w;
}

/** 番号つきの丸バッジ。 */
function badge(d, cx, cy, label, color, r = 14, size = 14) {
  circle(d, cx, cy, r, color);
  tx(d, cx, cy + size * 0.36, label, { size, color: '#fff', weight: 700, anchor: 'middle' });
}

/** 見出し帯つきカード。lines は文字列か {t,color,weight,size}。 */
function card(d, x, y, w, h, tone, title, lines = [], o = {}) {
  const hh = o.hh ?? (o.sub ? 62 : 46);
  const rx = 12;
  rc(d, x, y, w, h, { fill: '#fff', rx });
  pth(d, `M${x} ${y + hh} V${y + rx} Q${x} ${y} ${x + rx} ${y} H${x + w - rx} Q${x + w} ${y} ${x + w} ${y + rx} V${y + hh} Z`, { fill: tone.f });
  pth(d, `M${x} ${y + hh} H${x + w}`, { stroke: tone.s, sw: 1.4 });
  rc(d, x, y, w, h, { fill: 'none', stroke: tone.c, rx, sw: o.dash ? 1.8 : 1.6, dash: o.dash });
  const center = o.align === 'middle';
  const tX = center ? x + w / 2 : x + 18 + (o.badge ? 30 : 0);
  if (o.badge) badge(d, x + 30, y + (o.sub ? 31 : hh / 2), o.badge, tone.c, 13, 13.5);
  const tY = o.sub ? y + 28 : y + hh / 2 + 6.5;
  tx(d, tX, tY, title, { size: o.ts ?? 17.5, color: tone.t, weight: 700, anchor: center ? 'middle' : 'start', maxW: w - 36 - (o.badge ? 30 : 0) });
  if (o.sub) tx(d, tX, y + 50, o.sub, { size: 13, color: MUTED, anchor: center ? 'middle' : 'start', maxW: w - 36 - (o.badge ? 30 : 0) });
  const lh = o.lh ?? 23;
  let ly = y + hh + (o.top ?? 28);
  for (const raw of lines) {
    const ln = typeof raw === 'string' ? { t: raw } : raw;
    if (ln.gap) { ly += ln.gap; continue; }
    const size = ln.size ?? o.ls ?? 14.5;
    const lx = center ? x + w / 2 : x + 18 + (ln.indent ?? 0);
    tx(d, lx, ly, ln.t, { size, color: ln.color ?? INK, weight: ln.weight ?? 400, anchor: center ? 'middle' : 'start', maxW: w - 36 - (ln.indent ?? 0) });
    ly += ln.lh ?? lh;
  }
  return { x, y, w, h, cx: x + w / 2, bottom: y + h, right: x + w };
}

/** SysML の要素ボックス（«requirement» «block» «testCase»）。rows は本文の行。 */
function elemBox(d, x, y, w, tone, { stereo, name, rows = [], h: fixedH }) {
  const hh = 54;
  const h = fixedH ?? hh + 16 + rows.length * 21 + 8;
  rc(d, x, y, w, h, { fill: '#fff', rx: 10 });
  pth(d, `M${x} ${y + hh} V${y + 10} Q${x} ${y} ${x + 10} ${y} H${x + w - 10} Q${x + w} ${y} ${x + w} ${y + 10} V${y + hh} Z`, { fill: tone.f });
  pth(d, `M${x} ${y + hh} H${x + w}`, { stroke: tone.c, sw: 1.2 });
  rc(d, x, y, w, h, { fill: 'none', stroke: tone.c, rx: 10, sw: 1.8 });
  tx(d, x + w / 2, y + 20, `«${stereo}»`, { size: 12.5, color: tone.c, anchor: 'middle' });
  tx(d, x + w / 2, y + 42, name, { size: 16.5, color: tone.t, weight: 700, anchor: 'middle', maxW: w - 20 });
  let ly = y + hh + 24;
  for (const raw of rows) {
    const ln = typeof raw === 'string' ? { t: raw } : raw;
    tx(d, x + 14, ly, ln.t, { size: ln.size ?? 13.5, color: ln.color ?? INK, weight: ln.weight ?? 400, maxW: w - 28 });
    ly += 21;
  }
  return { x, y, w, h, cx: x + w / 2, cy: y + h / 2, bottom: y + h, right: x + w };
}

function reqBox(d, x, y, w, tone, { name, id, text, h }) {
  return elemBox(d, x, y, w, tone, {
    stereo: 'requirement',
    name,
    h,
    rows: [{ t: `id = ${id}`, color: tone.c, weight: 700, size: 13 }, { t: 'text =', color: MUTED, size: 12 }, ...text],
  });
}

/** SysML のコメント（«rationale» など）：右上が折れた付箋。 */
function noteBox(d, x, y, w, h, tone, lines) {
  const f = 14;
  pth(d, `M${x} ${y} H${x + w - f} L${x + w} ${y + f} V${y + h} H${x} Z`, { fill: '#fff', stroke: tone.c, sw: 1.5 });
  pth(d, `M${x + w - f} ${y} V${y + f} H${x + w}`, { stroke: tone.c, sw: 1.2 });
  lines.forEach((raw, i) => {
    const ln = typeof raw === 'string' ? { t: raw } : raw;
    tx(d, x + 14, y + 24 + i * 21, ln.t, { size: ln.size ?? 13.5, color: ln.color ?? INK, weight: ln.weight ?? 400, maxW: w - 28 });
  });
}

/** UML のクラス（名前・属性・操作の 3 区画）。 */
function classBox(d, x, y, w, tone, { stereo, name, jp, attrs = [], ops = [], nameSize = 15, rowSize = 12.5 }) {
  let hy = y + 8;
  const head = [];
  if (stereo) { hy += 15; head.push([hy, `«${stereo}»`, 12, tone.c, 400]); }
  hy += 19; head.push([hy, name, nameSize, tone.t, 700]);
  if (jp) { hy += 17; head.push([hy, jp, 12.5, MUTED, 400]); }
  const hh = hy - y + 11;
  const ah = attrs.length ? attrs.length * 19 + 10 : 12;
  const oh = ops.length ? ops.length * 19 + 10 : 12;
  const h = hh + ah + oh;
  rc(d, x, y, w, h, { fill: '#fff', rx: 4 });
  rc(d, x, y, w, hh, { fill: tone.f, rx: 4 });
  pth(d, `M${x} ${y + hh} H${x + w} M${x} ${y + hh + ah} H${x + w}`, { stroke: tone.c, sw: 1.2 });
  rc(d, x, y, w, h, { fill: 'none', stroke: tone.c, rx: 4, sw: 1.8 });
  head.forEach(([yy, s, size, color, weight]) => tx(d, x + w / 2, yy, s, { size, color, weight, anchor: 'middle', maxW: w - 12 }));
  attrs.forEach((s, i) => tx(d, x + 9, y + hh + 19 + i * 19, s, { size: rowSize, color: INK, maxW: w - 16 }));
  ops.forEach((s, i) => tx(d, x + 9, y + hh + ah + 19 + i * 19, s, { size: rowSize, color: INK, maxW: w - 16 }));
  return { x, y, w, h, cx: x + w / 2, bottom: y + h, right: x + w };
}

/** 一覧などに使う小さなチップ。dot は構造/振る舞い/要求の色。 */
function chip(d, x, y, w, h, label, o = {}) {
  rc(d, x, y, w, h, { fill: o.fill ?? '#fff', stroke: o.stroke ?? '#cbd5e1', rx: 8, sw: o.sw ?? 1.3 });
  let tX = x + 14;
  if (o.dot) { circle(d, x + 17, y + (o.sub ? 24 : h / 2), 5.5, CAT[o.dot]); tX = x + 31; }
  const mainY = o.sub ? y + 47 : y + h / 2 + 5.5;
  if (o.sub) tx(d, tX, y + 24 + 4.5, o.sub, { size: 12.5, color: MUTED, maxW: x + w - tX - 10 });
  tx(d, tX, mainY, label, { size: o.size ?? 15, color: o.color ?? INK, weight: 700, maxW: x + w - tX - (o.abbr ? 46 : 10) });
  if (o.abbr) tx(d, x + w - 12, mainY, o.abbr, { size: 13, color: MUTED, weight: 700, anchor: 'end' });
}

/** 図の仕上げ：本文の最下端から脚注の高さを計算して書き出す。 */
function done(d, contentEnd, notes) {
  notes.forEach((n) => fit(n, 16, 1120));
  d.finish(contentEnd + 30 + notes.length * 27 + 48, notes);
}

function start(file, title, subtitle) {
  current = file;
  fit(title, 27, 1144);
  fit(subtitle, 16, 1144);
  return new Drawing(file, title, subtitle);
}

